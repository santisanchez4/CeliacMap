"""scripts/build_barrios.py and the attribution of the barrio boundaries the chat uses (docs/DECISIONS.md,
«Barrios del chat por coordenadas»)."""

from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("build_barrios", ROOT / "scripts/build_barrios.py")
build_barrios = importlib.util.module_from_spec(spec)
spec.loader.exec_module(build_barrios)


def test_utm21s_origin_of_the_zone_is_the_central_meridian_on_the_equator():
    lng, lat = build_barrios.utm21s_to_lnglat(500000.0, 10000000.0)
    assert abs(lng + 57.0) < 1e-9 and abs(lat) < 1e-9


def test_utm21s_lands_in_montevideo_for_a_montevideo_easting_northing():
    lng, lat = build_barrios.utm21s_to_lnglat(574500.0, 6136000.0)
    assert -56.25 < lng < -56.15 and -34.95 < lat < -34.85


def test_simplify_keeps_the_corners_of_a_square_and_drops_points_on_its_sides():
    step = 0.0001  # ~10 m
    side = [(-56.2 + i * step, -34.9) for i in range(10)]
    up = [(-56.2 + 9 * step, -34.9 + i * step) for i in range(1, 10)]
    back = [(-56.2 + (9 - i) * step, -34.9 + 9 * step) for i in range(1, 10)]
    down = [(-56.2, -34.9 + (9 - i) * step) for i in range(1, 10)]
    ring = side + up + back + down
    simple = build_barrios.simplify_ring(ring, 2.0)
    assert len(simple) <= 6
    for corner in [(-56.2, -34.9), (-56.2 + 9 * step, -34.9 + 9 * step)]:
        assert any(abs(x - corner[0]) < 1e-12 and abs(y - corner[1]) < 1e-12 for x, y in simple)
    assert build_barrios.ring_contains(simple, -56.2 + 4 * step, -34.9 + 4 * step)
    assert not build_barrios.ring_contains(simple, -56.19, -34.9 + 4 * step)


def test_the_generated_data_carries_both_sources_and_licences():
    header = (ROOT / "supabase/functions/chat/barrios_data.ts").read_text(encoding="utf-8")[:2000]
    assert "GENERATED by scripts/build_barrios.py" in header
    assert "Intendencia de Montevideo" in header and "resolución 640/10" in header and "Instituto Nacional de Estadística" in header
    assert "Gobierno de la Ciudad Autónoma de Buenos Aires" in header and "CC BY 2.5 AR" in header


def test_the_site_credits_the_barrio_sources():
    html = (ROOT / "index.html").read_text(encoding="utf-8")
    assert 'class="footer-sources"' in html
    assert "Intendencia de Montevideo" in html and "Res. 640/10" in html
    assert "Gobierno de la Ciudad de Buenos Aires" in html
    assert "https://creativecommons.org/licenses/by/2.5/ar/" in html
