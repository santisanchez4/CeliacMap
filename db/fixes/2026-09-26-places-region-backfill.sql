  select count(*) into bad from public.places where status = 'approved' and region is null;
  if bad <> 0 then raise exception 'approved places without region: %', bad; end if;

  select count(*) into bad from public.places where region is null;
  if bad <> 49 then raise exception 'expected 49 places left without region, got %', bad; end if;

  select count(*) into bad from public.places
   where region is null and status <> 'discarded' and country in ('Argentina', 'Uruguay');
  if bad <> 0 then raise exception 'in-scope, non-discarded places without region: %', bad; end if;

  select count(*) into bad from public.places
